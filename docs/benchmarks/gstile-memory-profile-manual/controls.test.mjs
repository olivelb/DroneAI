import assert from 'node:assert/strict';
import {cadenceSummary,series,runSpec} from './controls.mjs';
const policy={durationMs:6000,minimumFrames:180,maximumMedianGapMs:40,maximumGapMs:250};
const samples=gap=>Array.from({length:Math.floor(6000/gap)},(_,i)=>({at:(i+1)*gap,focus:true,visibility:'visible'}));
let cases=0;
function test(fn){fn();cases++;}
test(()=>assert(cadenceSummary(samples(7),6000,policy).healthy));
test(()=>assert(cadenceSummary(samples(16),6000,policy).healthy));
test(()=>assert(!cadenceSummary(samples(1000),6000,policy).healthy));
test(()=>assert(!cadenceSummary([],6000,policy).healthy));
test(()=>assert(!cadenceSummary(samples(7),5000,policy).healthy));
test(()=>{const f=samples(7);f[30].focus=false;assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>{const f=samples(7);f[30].visibility='hidden';assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>assert(!cadenceSummary(samples(7).filter(f=>f.at<1000||f.at>2000),6000,policy).healthy));
test(()=>assert(!cadenceSummary(samples(7).filter(f=>f.at>1000),6000,policy).healthy));
test(()=>assert(!cadenceSummary(samples(7).filter(f=>f.at<5000),6000,policy).healthy));
test(()=>{const f=samples(7);f[10].at=NaN;assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>{const f=samples(7);f[10].at=f[9].at;assert(cadenceSummary(f,6000,policy).healthy);});
test(()=>{const f=samples(7);f[49].at=f[48].at;f[585].at=f[584].at;assert(cadenceSummary(f,6000,policy).healthy);});
test(()=>{const f=samples(7);f[10].at=f[9].at-0.1;assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>assert(!cadenceSummary(Array.from({length:900},()=>({at:3000,focus:true,visibility:'visible'})),6000,policy).healthy));
test(()=>{const f=samples(1000).flatMap(s=>Array.from({length:100},()=>({...s})));assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>{const f=samples(7);f.at(-1).at=6001;assert(!cadenceSummary(f,6000,policy).healthy);});
test(()=>assert.equal(series(6).length,14));
test(()=>assert.deepEqual(series(2).map(r=>r.arm),['reference','candidate','reference','candidate','candidate','reference']));
test(()=>assert.equal(runSpec('fg-test',4,6).label,'fg-test-pair-2-candidate'));
test(()=>{for(const i of [-1,14,NaN,1.5])assert.throws(()=>runSpec('fg-test',i,6));});
test(()=>{for(const s of ['', '../test','bad name','a'.repeat(100)])assert.throws(()=>runSpec(s,0,6));});
test(()=>{for(const p of [0,1.5,21])assert.throws(()=>series(p));});
console.log(`${cases} foreground-control tests passed`);
